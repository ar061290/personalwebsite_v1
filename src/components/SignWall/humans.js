/** The traced signatures: { name, msg, date, seed, size?, strokes: [{ c, g, p }] }, newest first. */
export const HUMANS = RAW.map(([name, msg, date, seed, strokes, size]) => {
  const rng = createRng(seed * 7 + 3)
  return {
    name,
    msg,
    date,
    seed,
    ...(size ? { size } : {}),
    strokes: strokes.map(([c, path, v = DEFAULT_V, hold], i) => ({
      c,
      g: i ? 10 + ((rng() * 18) | 0) : 0,
      p: frames(densify(path, 1.5), rng, { v, hold: hold ?? 2 + ((rng() * 5) | 0) }),
    })),
  }
})

/** HUMANS as wall entries ({ t } from the date), the way wall.js lays them out. */
export function humanEntries(size = 18, ink = 6) {
  return HUMANS.map((h, i) => ({
    id: `h${i}`,
    curated: true,
    name: h.name,
    msg: h.msg,
    t: Date.parse(h.date + 'T12:00:00'),
    seed: h.seed,
    size: h.size || size,
    ink,
    strokes: h.strokes,
  }))
}

/**
 * A smooth dense curve through the traced points (uniform Catmull-Rom), about `step` px apart,
 * so frames() can read the curvature from neighbouring samples.
 */
function densify(pts, step) {
  const n = pts.length / 2
  if (n < 2) return pts.slice()
  const P = (i) => {
    const k = Math.min(n - 1, Math.max(0, i))
    return [pts[k * 2], pts[k * 2 + 1]]
  }
  const out = [pts[0], pts[1]]
  for (let i = 0; i < n - 1; i++) {
    const [x0, y0] = P(i - 1)
    const [x1, y1] = P(i)
    const [x2, y2] = P(i + 1)
    const [x3, y3] = P(i + 2)
    const m = Math.max(1, Math.ceil(Math.hypot(x2 - x1, y2 - y1) / step))
    for (let j = 1; j <= m; j++) {
      const t = j / m
      const t2 = t * t
      const t3 = t2 * t
      out.push(
        0.5 * (2 * x1 + (x2 - x0) * t + (2 * x0 - 5 * x1 + 4 * x2 - x3) * t2 + (3 * x1 - x0 - 3 * x2 + x3) * t3),
        0.5 * (2 * y1 + (y2 - y0) * t + (2 * y0 - 5 * y1 + 4 * y2 - y3) * t2 + (3 * y1 - y0 - 3 * y2 + y3) * t3),
      )
    }
  }
  return out
}

/**
 * Walks a dense polyline at handwriting speed: ~v px per frame on the straights, slower in tight
 * turns (speed grows with the cube root of the radius of curvature), easing in after `hold`
 * frames of resting tip. Returns [start, frame1, frame2, ...] as the brush replays them.
 */
function frames(poly, rng, { v, hold }) {
  const n = poly.length / 2
  const len = new Float64Array(n)
  for (let i = 1; i < n; i++)
    len[i] = len[i - 1] + Math.hypot(poly[i * 2] - poly[i * 2 - 2], poly[i * 2 + 1] - poly[i * 2 - 1])
  const speed = new Float64Array(n)
  const K = 3
  for (let i = 0; i < n; i++) {
    const a = Math.max(0, i - K)
    const b = Math.min(n - 1, i + K)
    const ax = poly[i * 2] - poly[a * 2]
    const ay = poly[i * 2 + 1] - poly[a * 2 + 1]
    const bx = poly[b * 2] - poly[i * 2]
    const by = poly[b * 2 + 1] - poly[i * 2 + 1]
    const turn = Math.abs(Math.atan2(ax * by - ay * bx, ax * bx + ay * by))
    const seg = Math.max(1e-3, len[b] - len[a])
    const R = seg / Math.max(1e-3, turn)
    speed[i] = Math.min(2.6, Math.max(0.4, Math.cbrt(R / 22))) * v
  }
  const total = len[n - 1]
  const out = [q(poly[0]), q(poly[1])]
  for (let i = 0; i < hold; i++) out.push(out[0], out[1])
  let s = 0
  let j = 0
  let f = 0
  const jitter = 0.85 + rng() * 0.3
  while (s < total) {
    while (j < n - 2 && len[j + 1] < s) j++
    s += speed[j] * jitter * Math.min(1, (f + 1) / 6)
    f++
    while (j < n - 2 && len[j + 1] < s) j++
    const t = Math.min(1, Math.max(0, (s - len[j]) / Math.max(1e-6, len[j + 1] - len[j])))
    out.push(q(poly[j * 2] + (poly[j * 2 + 2] - poly[j * 2]) * t), q(poly[j * 2 + 1] + (poly[j * 2 + 3] - poly[j * 2 + 1]) * t))
  }
  return out
}
